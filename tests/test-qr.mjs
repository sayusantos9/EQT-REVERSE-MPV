import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(new URL(p,import.meta.url),'utf8');
// Smoke tests independentes do Expo para rodar somente com Node.
const catalog=read('../src/data/catalog.js');
const builtIns=Function(catalog.replace(/export const /g,'const ')+';return CATEGORIES;')();
const code=read('../src/services/qrSector.js').replace(/import \{CATEGORIES\} from '\.\.\/data\/catalog';/,'').replace(/export (const|function) /g,'$1 ');
const {encodeQr,decodeQr}=Function('CATEGORIES',code+';return {encodeQr,decodeQr};')(builtIns);
const qr=encodeQr('CABOS','Almoxarifado');
assert.equal(qr,'EQT:V1:CABOS:ALMOXARIFADO');
assert.deepEqual(decodeQr(qr),{id:'CABOS',sector:'Almoxarifado',version:'V1'});
assert.equal(decodeQr('MR:CAT:LAMPADAS')?.id,'LAMPADAS');
assert.equal(decodeQr('EQT:V1:INVALIDO:AMBIENTAL'),null);
const custom={id:'CMANUAL123',name:'Transformadores'};
assert.deepEqual(decodeQr(encodeQr(custom.id,'Ambiental',[...builtIns,custom]),[...builtIns,custom]).id,custom.id);
assert.throws(()=>encodeQr('INVALIDO','Ambiental'));
const perms=read('../src/navigation/permissions.js').replace(/export (const|function) /g,'$1 ');
const {canAccess,NAV_ITEMS}=Function(perms+';return {canAccess,NAV_ITEMS};')();
assert(canAccess('administrador','adminCodes'));
assert(canAccess('administrador','addCategory'));
assert(!canAccess('administrador','sorting'));
assert(!canAccess('administrador','missions'));
assert(!canAccess('colaborador','staff'));
assert(!canAccess('colaborador','qrLabel'));
assert(canAccess('colaborador','flashcards'));
assert.deepEqual(Object.keys(NAV_ITEMS).sort(),['administrator','collaborator']);
const games=read('../src/screens/GameScreens.js');
assert(games.includes('Animated.timing'));
assert(games.includes('rotateY'));
assert(!games.includes('PanResponder.create'));
assert(games.includes('onPress={()=>select(r.id)}'));
console.log('OK — QR por setor, categorias locais, permissões, flashcards e minijogo por toque.');
